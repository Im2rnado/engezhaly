const normalize = (value: string) => value.replace(/\s+/g, " ").trim();

export function translateUiText(value: string, lang: "en" | "ar"): string {
  if (lang !== "ar" || !value) return value;
  const normalized = normalize(value);
  const exact = ARABIC_UI[normalized];
  if (exact) return value.replace(normalized, exact);

  const statusMatch = normalized.match(/^(Status|Type):\s*(.+)$/i);
  if (statusMatch) {
    const label = statusMatch[1].toLowerCase() === "status" ? "الحالة" : "النوع";
    const translatedValue = ARABIC_UI[statusMatch[2]] || statusMatch[2];
    return `${label}: ${translatedValue}`;
  }

  const countPatterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^(\d+)\s+days?$/i, (m) => `${m[1]} أيام`],
    [/^(\d+)\s+hours?$/i, (m) => `${m[1]} ساعات`],
    [/^(\d+)\s+minutes?$/i, (m) => `${m[1]} دقيقة`],
    [/^(\d+)\s+orders?$/i, (m) => `${m[1]} طلبات`],
    [/^(\d+)\s+jobs?$/i, (m) => `${m[1]} وظائف`],
  ];
  for (const [pattern, replacer] of countPatterns) {
    const match = normalized.match(pattern);
    if (match) return replacer(match);
  }

  return value;
}
